-- One row per player: login, profile, wallet balances and streak all live here.

CREATE TABLE clients (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             uuid NOT NULL UNIQUE DEFAULT uuidv7(),  -- public player id (leaderboards)
    -- login
    username         varchar(100) NOT NULL UNIQUE,
    email            varchar(255) NOT NULL UNIQUE,
    phone            varchar(20) UNIQUE,
    password         varchar(255) NOT NULL,
    status           varchar(20) NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'pending', 'blocked', 'deleted')),
    refresh_token    varchar(512),
    -- profile ('' full_name = not set up yet; the backend fills it from username)
    full_name        varchar(100) NOT NULL DEFAULT '',
    avatar_id        varchar(50) NOT NULL DEFAULT 'user',
    avatar_url       varchar(255),
    class            varchar(50),
    board            varchar(100),
    subjects         text NOT NULL DEFAULT '[]',             -- JSON array written by the backend
    is_onboarded     boolean NOT NULL DEFAULT false,
    -- wallet balances (every change is also in wallet_ledger)
    coins            integer NOT NULL DEFAULT 100 CHECK (coins >= 0),
    gems             integer NOT NULL DEFAULT 10 CHECK (gems >= 0),
    experience       integer NOT NULL DEFAULT 0 CHECK (experience >= 0),
    level            integer NOT NULL DEFAULT 1 CHECK (level >= 1),
    weekly_score     integer NOT NULL DEFAULT 0,
    -- streak
    current_streak   integer NOT NULL DEFAULT 1 CHECK (current_streak >= 0),
    highest_streak   integer NOT NULL DEFAULT 1 CHECK (highest_streak >= 0),
    last_active_date date NOT NULL DEFAULT CURRENT_DATE,
    active_days      date[] NOT NULL DEFAULT ARRAY[CURRENT_DATE],  -- last 31 days played
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- Weekly leaderboard rebuild reads only players with a score, highest first.
CREATE INDEX idx_clients_weekly_score
    ON clients (weekly_score DESC) INCLUDE (id)
    WHERE weekly_score > 0;

-- Append-only; uuidv7 keeps inserts at the right edge of the primary-key index.
CREATE TABLE wallet_ledger (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    client_id        integer NOT NULL REFERENCES clients (id) ON DELETE CASCADE,
    transaction_type varchar(50) NOT NULL,
    direction        varchar(10) NOT NULL DEFAULT 'credit' CHECK (direction IN ('credit', 'debit')),
    amount           integer NOT NULL CHECK (amount > 0),
    currency         varchar(20) NOT NULL CHECK (currency IN ('coins', 'gems', 'experience')),
    balance_after    integer NOT NULL DEFAULT 0,
    reference_id     varchar(64),
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_wallet_ledger_client_created ON wallet_ledger (client_id, created_at DESC);
